"""Compile the pinned MIT Hunspell inventory for offline PDF word validation.

Usage: python scripts/build-turkish-word-forms.py /path/to/downloaded/tr
Input files: index.dic, index.aff, license from wooorm/dictionaries/dictionaries/tr.
This deliberately supports only this inventory's explicit, nonrecursive suffix
assignments. Unsupported affix features fail instead of admitting guessed forms.
"""

import base64
import gzip
import hashlib
import json
from pathlib import Path
import sys
import unicodedata


def normalize(word):
    return (
        unicodedata.normalize("NFC", word)
        .replace("I", "ı")
        .replace("İ", "i")
        .lower()
        .replace("’", "")
        .replace("'", "")
        .translate(str.maketrans("âîû", "aiu"))
    )


source = Path(sys.argv[1])
destination = Path(__file__).resolve().parent.parent / "lib/turkish-word-forms"
checksums = json.loads((destination / "source.json").read_text())["sha256"]
for name, expected in checksums.items():
    assert hashlib.sha256((source / name).read_bytes()).hexdigest() == expected, name

suffixes = {}
for line in (source / "index.aff").read_text().splitlines():
    fields = line.split()
    if not fields:
        continue
    if fields[0] == "SFX":
        if len(fields) == 4:
            assert fields[2:] == ["N", "1"], fields
        else:
            assert len(fields) == 5 and fields[2] == "0" and fields[4] == ".", fields
            assert "/" not in fields[3], fields
            suffixes[int(fields[1])] = normalize(fields[3])
    else:
        assert fields[0] in {"LANG", "SET", "TRY", "FLAG"}, fields
        if fields[0] == "FLAG":
            assert fields[1] == "num"

words = {}
rows = (source / "index.dic").read_text().splitlines()
assert len(rows) - 1 == int(rows[0])
for row in rows[1:]:
    word, separator, flags = row.partition("/")
    word = normalize(word)
    if not word.isalpha():
        continue
    allowed = words.setdefault(word, set())
    if separator:
        assigned = {int(flag) for flag in flags.split(",")}
        assert assigned <= suffixes.keys(), row
        allowed.update(assigned)

# Keep the explicitly assigned endings, rather than expanding 1.3 million
# combinations into a large runtime dictionary. Sorted UTF-8 rows can be searched
# directly in a Buffer, without allocating hundreds of thousands of JS objects.
header = json.dumps(suffixes, ensure_ascii=False, separators=(",", ":"))
table = "\n".join(
    word + "|" + ",".join(map(str, sorted(flags)))
    for word, flags in sorted(words.items())
)
raw = (header + "\n" + table + "\n").encode()
encoded = base64.b64encode(gzip.compress(raw, compresslevel=9, mtime=0)).decode()
(destination / "data.ts").write_text(
    "// Generated by scripts/build-turkish-word-forms.py. Do not edit.\n"
    "// MIT: Copyright (c) 2014 Harun Reşit Zafer; see LICENSE and source.json.\n"
    "export const compressedWordForms =\n  \"" + encoded + "\";\n"
)
print(json.dumps({"stems": len(words), "rawBytes": len(raw), "gzipBytes": len(base64.b64decode(encoded))}))
